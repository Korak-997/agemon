import { execFileSync, spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdtemp, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { errorMessage } from "../src/core/error-message.js";
import {
  ESSENTIALS_SKILLS_COMMIT,
  ESSENTIALS_SKILLS_REPOSITORY_URL,
} from "../src/plugins/pins.js";
import {
  BUNDLE_FINGERPRINTS,
  type BundleFingerprints,
} from "../src/plugins/skills/bundle-fingerprints.js";
import { SKILL_GROUPS } from "../src/plugins/skills/catalog.js";
import {
  resolvePinnedSkillsSourceDirectory,
  skillPathInRepository,
} from "../src/plugins/skills/pinned-source.js";
import { fingerprintSkillSource } from "../src/plugins/skills/skill-tree.js";

const REPOSITORY_ROOT = resolve(fileURLToPath(import.meta.url), "../..");
const VENDORED_SKILLS_PATH = "assets/skills";
const OUTPUT_PATH = join(
  REPOSITORY_ROOT,
  "src/plugins/skills/bundle-fingerprints.ts",
);
const RELEASE_TAG_PATTERN = "v*";
const V6_DEVELOPMENT_REVISIONS = [
  "872f9b525876803759049394329537aa2a0e39b3",
  "f63623d2ce51ce3e6a5914c4e6049a1f11be8204",
  "4e69a7f5e2c6ba36f3ce96a19c506713211f36f1",
];
const SKILL_MANIFEST_FILE = "SKILL.md";
const MAX_SKILL_DIRECTORY_DEPTH = 3;
const MAX_ARCHIVE_BYTES = 256 * 1024 * 1024;
const GIT_WITHOUT_HOOKS = ["-c", "core.hooksPath=/dev/null"];
const OUTPUT_HEADER =
  "// Generated by scripts/skill-fingerprints.ts; run `npm run skills:fingerprints` instead of editing.";

type FingerprintsByName = Map<string, Set<string>>;
type UnreadableSkill = "warn" | "fail";

function git(args: string[], cwd = REPOSITORY_ROOT): string {
  return execFileSync("git", [...GIT_WITHOUT_HOOKS, ...args], {
    cwd,
    encoding: "utf8",
    env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1" },
  }).trim();
}

function byCodeUnit(left: string, right: string): number {
  if (left === right) {
    return 0;
  }
  return left < right ? -1 : 1;
}

function addFingerprint(
  target: FingerprintsByName,
  skillName: string,
  fingerprint: string,
): void {
  const fingerprints = target.get(skillName) ?? new Set<string>();
  fingerprints.add(fingerprint);
  target.set(skillName, fingerprints);
}

async function findSkillDirectories(
  directory: string,
  depth = 1,
): Promise<string[]> {
  if (depth > MAX_SKILL_DIRECTORY_DEPTH) {
    return [];
  }
  const entries = await readdir(directory, { withFileTypes: true });
  if (entries.some((entry) => entry.name === SKILL_MANIFEST_FILE)) {
    return [directory];
  }
  const nested = await Promise.all(
    entries
      .filter((entry) => entry.isDirectory())
      .map((entry) =>
        findSkillDirectories(join(directory, entry.name), depth + 1),
      ),
  );
  return nested.flat();
}

async function fingerprintVendoredTree(
  skillsRoot: string,
  label: string,
  onUnreadable: UnreadableSkill,
): Promise<FingerprintsByName> {
  const fingerprints: FingerprintsByName = new Map();
  if (!existsSync(skillsRoot)) {
    return fingerprints;
  }
  for (const skillDirectory of await findSkillDirectories(skillsRoot)) {
    const skillName = skillDirectory.split("/").at(-1) ?? "";
    try {
      addFingerprint(
        fingerprints,
        skillName,
        await fingerprintSkillSource(skillDirectory),
      );
    } catch (error) {
      const problem = `${label} ${relative(skillsRoot, skillDirectory)}: ${errorMessage(error)}`;
      if (onUnreadable === "fail") {
        throw new Error(`Could not fingerprint ${problem}`);
      }
      console.warn(`Skipped ${problem}`);
    }
  }
  return fingerprints;
}

function resolveCommit(revision: string): string {
  return git([
    "rev-parse",
    "--verify",
    "--end-of-options",
    `${revision}^{commit}`,
  ]);
}

function commitHasVendoredSkills(commit: string): boolean {
  return (
    spawnSync(
      "git",
      [
        ...GIT_WITHOUT_HOOKS,
        "cat-file",
        "-e",
        "--end-of-options",
        `${commit}:${VENDORED_SKILLS_PATH}`,
      ],
      { cwd: REPOSITORY_ROOT },
    ).status === 0
  );
}

async function fingerprintRevision(
  revision: string,
  onUnreadable: UnreadableSkill,
): Promise<FingerprintsByName> {
  const commit = resolveCommit(revision);
  if (!commitHasVendoredSkills(commit)) {
    return new Map();
  }
  const extractDirectory = await mkdtemp(join(tmpdir(), "agemon-skill-fp-"));
  try {
    const archive = execFileSync(
      "git",
      [
        ...GIT_WITHOUT_HOOKS,
        "archive",
        "--format=tar",
        "--end-of-options",
        commit,
        VENDORED_SKILLS_PATH,
      ],
      { cwd: REPOSITORY_ROOT, maxBuffer: MAX_ARCHIVE_BYTES },
    );
    const extraction = spawnSync("tar", ["-x", "-C", extractDirectory], {
      input: archive,
    });
    if (extraction.status !== 0) {
      throw new Error(`tar failed for ${revision}: ${extraction.stderr}`);
    }
    return await fingerprintVendoredTree(
      join(extractDirectory, VENDORED_SKILLS_PATH),
      revision,
      onUnreadable,
    );
  } finally {
    await rm(extractDirectory, { recursive: true, force: true });
  }
}

function releaseTags(): string[] {
  const output = git(["tag", "-l", RELEASE_TAG_PATTERN]);
  return output === "" ? [] : output.split("\n");
}

function pinnedSkillNames(commit: string): string[] {
  return SKILL_GROUPS.flatMap((group) => group.skills)
    .filter((entry) => entry.pinnedRepository?.commit === commit)
    .map((entry) => entry.skillName);
}

function isolatedGit(directory: string, args: string[]): string {
  return execFileSync("git", [...GIT_WITHOUT_HOOKS, ...args], {
    cwd: directory,
    encoding: "utf8",
    env: {
      ...process.env,
      GIT_CONFIG_GLOBAL: "/dev/null",
      GIT_CONFIG_NOSYSTEM: "1",
      GIT_DIR: join(directory, ".git"),
      GIT_WORK_TREE: directory,
    },
  }).trim();
}

function isPristineCheckout(directory: string, commit: string): boolean {
  try {
    return (
      isolatedGit(directory, ["rev-parse", "HEAD"]) === commit &&
      isolatedGit(directory, [
        "-c",
        "core.fsmonitor=false",
        "status",
        "--porcelain",
        "--ignored",
      ]) === ""
    );
  } catch {
    return false;
  }
}

async function freshPinnedCheckout(commit: string): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), "agemon-pinned-skills-"));
  isolatedGit(directory, ["init", "-q"]);
  isolatedGit(directory, [
    "fetch",
    "--depth",
    "1",
    "--end-of-options",
    ESSENTIALS_SKILLS_REPOSITORY_URL,
    commit,
  ]);
  isolatedGit(directory, ["checkout", "-q", "FETCH_HEAD"]);
  if (!isPristineCheckout(directory, commit)) {
    throw new Error(`The fetched pinned skills are not at ${commit}.`);
  }
  return directory;
}

async function pinnedSourceDirectory(commit: string): Promise<string> {
  const cached = resolvePinnedSkillsSourceDirectory(commit);
  return isPristineCheckout(cached, commit)
    ? cached
    : freshPinnedCheckout(commit);
}

async function fingerprintPinnedSkills(
  commit: string,
): Promise<Record<string, string>> {
  const sourceDirectory = await pinnedSourceDirectory(commit);
  const fingerprints: Record<string, string> = {};
  for (const skillName of pinnedSkillNames(commit)) {
    fingerprints[skillName] = await fingerprintSkillSource(
      join(sourceDirectory, skillPathInRepository(skillName)),
    );
  }
  return fingerprints;
}

function mergeInto(
  target: FingerprintsByName,
  source: FingerprintsByName,
): void {
  for (const [skillName, fingerprints] of source) {
    for (const fingerprint of fingerprints) {
      addFingerprint(target, skillName, fingerprint);
    }
  }
}

function existingHistory(): FingerprintsByName {
  const history: FingerprintsByName = new Map();
  for (const [skillName, fingerprints] of Object.entries(
    BUNDLE_FINGERPRINTS.history,
  )) {
    for (const fingerprint of fingerprints) {
      addFingerprint(history, skillName, fingerprint);
    }
  }
  return history;
}

function sortedRecord<Value>(
  entries: Iterable<[string, Value]>,
): Record<string, Value> {
  return Object.fromEntries(
    [...entries].sort(([left], [right]) => byCodeUnit(left, right)),
  );
}

function renderModule(fingerprints: BundleFingerprints): string {
  return `${OUTPUT_HEADER}

export interface BundleFingerprints {
  history: Readonly<Record<string, readonly string[]>>;
  pinned: Readonly<Record<string, Readonly<Record<string, string>>>>;
}

export const BUNDLE_FINGERPRINTS: BundleFingerprints = ${JSON.stringify(fingerprints, null, 2)};
`;
}

async function releasedFingerprints(
  onUnreadable: UnreadableSkill,
): Promise<FingerprintsByName> {
  const released: FingerprintsByName = new Map();
  for (const tag of releaseTags()) {
    mergeInto(released, await fingerprintRevision(tag, onUnreadable));
  }
  return released;
}

function missingFrom(
  history: FingerprintsByName,
  expected: FingerprintsByName,
): string[] {
  const missing: string[] = [];
  for (const [skillName, fingerprints] of expected) {
    for (const fingerprint of fingerprints) {
      if (!history.get(skillName)?.has(fingerprint)) {
        missing.push(`${skillName} ${fingerprint}`);
      }
    }
  }
  return missing;
}

async function check(): Promise<void> {
  const expected = await releasedFingerprints("fail");
  mergeInto(
    expected,
    await fingerprintVendoredTree(
      join(REPOSITORY_ROOT, VENDORED_SKILLS_PATH),
      "working tree",
      "fail",
    ),
  );
  const missing = missingFrom(existingHistory(), expected);
  if (missing.length > 0) {
    throw new Error(
      `bundle-fingerprints.ts is missing ${missing.length} fingerprint(s) of released or current skills (${missing.slice(0, 5).join("; ")}). Run 'npm run skills:fingerprints' and commit the result.`,
    );
  }
  console.log(
    `Skill fingerprints cover ${releaseTags().length} release tag(s) and the working tree.`,
  );
}

async function write(): Promise<void> {
  const history = existingHistory();
  mergeInto(history, await releasedFingerprints("warn"));
  for (const revision of V6_DEVELOPMENT_REVISIONS) {
    mergeInto(history, await fingerprintRevision(revision, "warn"));
  }
  mergeInto(
    history,
    await fingerprintVendoredTree(
      join(REPOSITORY_ROOT, VENDORED_SKILLS_PATH),
      "working tree",
      "fail",
    ),
  );
  const pinned: Record<string, Record<string, string>> = {
    ...BUNDLE_FINGERPRINTS.pinned,
    [ESSENTIALS_SKILLS_COMMIT]: await fingerprintPinnedSkills(
      ESSENTIALS_SKILLS_COMMIT,
    ),
  };
  for (const [skillName, fingerprint] of Object.entries(
    pinned[ESSENTIALS_SKILLS_COMMIT],
  )) {
    addFingerprint(history, skillName, fingerprint);
  }

  await writeFile(
    OUTPUT_PATH,
    renderModule({
      history: sortedRecord(
        [...history].map(([skillName, fingerprints]) => [
          skillName,
          [...fingerprints].sort(byCodeUnit),
        ]),
      ),
      pinned: sortedRecord(
        Object.entries(pinned).map(([commit, fingerprints]) => [
          commit,
          sortedRecord(Object.entries(fingerprints)),
        ]),
      ),
    }),
  );
  execFileSync(
    join(REPOSITORY_ROOT, "node_modules/.bin/biome"),
    ["format", "--write", OUTPUT_PATH],
    { cwd: REPOSITORY_ROOT, stdio: "ignore" },
  );
  console.log(`Wrote ${relative(REPOSITORY_ROOT, OUTPUT_PATH)}.`);
}

try {
  await (process.argv.includes("--check") ? check() : write());
} catch (error) {
  console.error(errorMessage(error));
  process.exitCode = 1;
}
